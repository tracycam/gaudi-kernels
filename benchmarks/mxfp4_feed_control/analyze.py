"""Audit generated-feed placement/coverage, exact outputs and separate profiles.

TPC SPU halt is not a proof that asynchronous tensor stores have drained. Never
divide generated bytes by SPU-active time and label that SRAM store bandwidth.
"""
import argparse
import collections
import hashlib
import json
import math
from pathlib import Path
import statistics
import struct


def merge(intervals):
    out = []
    for lo, hi in sorted(intervals):
        assert hi >= lo
        if out and lo <= out[-1][1]:
            out[-1][1] = max(hi, out[-1][1])
        else:
            out.append([lo, hi])
    return out


def profile(path):
    events = json.loads(path.read_text())['traceEvents']
    processes = {e['pid']: e['args']['name'] for e in events
                 if e['ph'] == 'M' and e['name'] == 'process_name'}
    pending = collections.defaultdict(list)
    spans = collections.defaultdict(list)
    nodes = collections.defaultdict(list)
    markers = collections.Counter()
    for event in events:
        engine = next((k for k in ('TPC', 'MME')
                       if processes.get(event.get('pid'), '').startswith('*'+k)), None)
        if not engine or event['ph'] not in ('B', 'E'):
            continue
        a = event.get('args', {})
        key = (event['pid'], event['tid'], event['name'], a.get('id'),
               a.get('Unique Node ID'), a.get('recipe id'))
        markers[(engine, event['ph'], a.get('HW event name'))] += 1
        if event['ph'] == 'B':
            pending[key].append(event['ts'])
        else:
            assert pending[key], ('unmatched end', key)
            span = [pending[key].pop(0), event['ts']]
            spans[engine].append(span)
            nodes[(engine, event['name'])].append(span)
    assert all(not v for v in pending.values()) and spans['TPC'] and spans['MME']
    tpc, mme = merge(spans['TPC']), merge(spans['MME'])
    both = merge(tpc+mme)
    duration = lambda xs: sum(hi-lo for lo, hi in xs)
    origin = both[0][0]
    return dict(trace_sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
                span_us=both[-1][1]-origin,
                tpc_spu_union_us=duration(tpc), mme_union_us=duration(mme),
                spu_mme_overlap_us=duration(tpc)+duration(mme)-duration(both),
                neither_spu_nor_mme_us=both[-1][1]-origin-duration(both),
                event_markers=[dict(engine=k[0], phase=k[1], marker=k[2], count=v)
                               for k, v in markers.items()],
                node_envelopes=[dict(engine=k[0], name=k[1], start_us=min(a for a,b in v)-origin,
                                     end_us=max(b for a,b in v)-origin)
                                for k,v in sorted(nodes.items(), key=lambda item:min(a for a,b in item[1]))],
                scope='Separate profiled replay; SPU halt does not measure store drain; no bus/issue counter')


def audit(case):
    rows = [json.loads(s) for s in (case/'run.log').read_text().splitlines() if s.startswith('{')]
    plan = next(r for r in rows if r['stage'] == 'plan')
    outcome = json.loads((case/'exit.json').read_text())
    assert outcome['returncode'] == outcome['runner_exit_code'] == 0
    assert outcome['source_identity_verified'] and outcome['module'] == 5
    graph_path = case/'post_graph.json'
    if graph_path.is_dir():
        files = list(graph_path.glob('*.post.json'))
        assert len(files) == 1
        graph_path = files[0]
    graphs = json.loads(graph_path.read_text())['graphs']
    assert len(graphs) == 1
    graph = graphs[0]
    tensors = {t['name']:t for t in graph['tensors']}
    physical = [n for n in graph['nodes'] if not n['is_logical']]
    assert all(n['engine'] in ('TPC','MME') for n in physical)
    generators = [n for n in physical if n['engine'] == 'TPC']
    consumers = [n for n in physical if n['engine'] == 'MME']
    assert generators and len(generators) == len(consumers)
    E, N, K, M = (plan[k] for k in ('E','N','K','M'))
    width = plan['weight_element_bytes']
    shared = plan.get('layout') == 'shared-a-n'
    dtype = 'hfloat8' if width == 1 else 'bf16'
    assert not plan['real_mxfp4'] and not plan['activation_quantization_included']
    assert M == 2 and E in (8,32) and N == 512 and K == 6144
    seed_regions, sram_regions = [], []
    decoded = {}
    for node in generators:
        assert node['guid'] == 'gk_generated_feed_'+plan['mode']
        assert len(node['input_tensors']) == len(node['output_tensors']) == 1
        seed = tensors[node['input_tensors'][0]]
        w = tensors[node['output_tensors'][0]]
        wn,wk,count = w['max_shape']
        assert wk == K and (count == 1 if shared else wn == N)
        assert seed['max_shape'] == [wn,count]
        assert seed['allocation'] == 'DRAM' and seed['user_mem_section_index'] == tensors['seed']['user_mem_section_index']
        assert seed['dtype'] == w['dtype'] == dtype
        assert w['allocation'] == 'SRAM' and not w['persistent']
        assert w['strides'][:3] == [width,width*wn,width*wn*K]
        offset = seed['offset']-tensors['seed']['offset']
        assert offset % width == 0
        first = offset//width
        assert shared or first % N == 0
        seed_regions.append([first,first+wn*count])
        decoded[w['name']] = (first,wn,count)
        sram_regions.append([w['offset'],w['offset']+width*wn*K*count])
    cursor = 0
    for start,end in sorted(seed_regions):
        assert start == cursor, 'CSE, gap or duplicate expert interval'
        cursor = end
    assert cursor == E*N
    assert {n['input_tensors'][1] for n in consumers} == set(decoded)
    for node in consumers:
        # Synapse simplifies batch size one to GEMM in the shared-A layout.
        assert node['guid'] in (('gemm','batch_gemm') if shared else ('batch_gemm',))
        assert node['params'] == [0,0]
        first,wn,count = decoded[node['input_tensors'][1]]
        a = tensors[node['input_tensors'][0]]
        y = tensors[node['output_tensors'][0]]
        assert a['max_shape'] == [K,M,count] and a['dtype'] == dtype
        assert a['offset']-tensors['activation']['offset'] == (0 if shared else first//N*K*M*width)
        assert y['max_shape'] == [wn,M,count] and y['dtype'] == 'float32'
        assert y['offset']-tensors['output']['offset'] == first*(1 if shared else M)*4
        assert y['strides'][1] == (E*N if shared else N)*4
    assert plan['generated_weight_bytes'] == E*N*K*width
    assert plan['mxfp4_equivalent_bytes'] == E*N*K*17//32
    record = dict(case=case.name, plan=plan, pass_=True, source_commit=outcome['git_commit'],
                  graph_sha256=hashlib.sha256(graph_path.read_bytes()).hexdigest(),
                  generated_tpc_nodes=len(generators), mme_nodes=len(consumers),
                  seed_channel_intervals=sorted(seed_regions), expanded_weight_all_sram=True,
                  expanded_weight_elements_generated_and_consumed_once=True,
                  no_dma=True, sram_address_union_bytes=sum(b-a for a,b in merge(sram_regions)),
                  mme_strategies=sorted(set(n.get('mme_node_strategy','') for n in consumers)))
    if any(r['stage'] == 'compile_only' for r in rows):
        assert not (case/'output_checked.bin').exists()
        return record
    gate = next(r for r in rows if r['stage'] == 'correctness')
    assert gate['checked'] == E*M*N and gate['bad'] == 0 and gate['max_abs'] == 0
    actual = struct.unpack('<'+'f'*(E*M*N), (case/'output_checked.bin').read_bytes())
    values = (0,.5,1,1.5,2,3,4,6)
    for e in range(E):
        for m in range(M):
            for n in range(N):
                expected = values[(n+e*3)%8]*(-1 if (n//8+e)&1 else 1)*K*(m+1)
                index = (m*E+e if shared else e*M+m)*N+n
                assert actual[index] == expected
    times = [r for r in rows if r['stage'] == 'timing']
    assert len(times) == 5 and all(math.isfinite(r[k]) and r[k]>0 for r in times for k in ('event_us','wall_us'))
    event = statistics.median(r['event_us'] for r in times)
    traces = list((case/'trace').glob('*_7.json'))
    record.update(correctness=gate, independent_binary_oracle_pass=True,
                  samples=times, profiled='--profile' in outcome['command'],
                  event_median_us=event, wall_median_us=statistics.median(r['wall_us'] for r in times),
                  generated_feed_TBps=plan['generated_weight_bytes']/event/1e6,
                  equivalent_only_TBps=plan['mxfp4_equivalent_bytes']/event/1e6,
                  target_1_5_us=plan['mxfp4_equivalent_bytes']/1.5e6)
    if record['profiled']:
        assert len(traces) == 1
        record['profile'] = profile(traces[0])
        record['profile']['mme_logical_consumption_TBps'] = plan['generated_weight_bytes']/record['profile']['mme_union_us']/1e6
    return record


if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('root', type=Path, help='sealed source/build/results root')
    p.add_argument('--output', type=Path, required=True)
    args = p.parse_args()
    manifest = json.loads((args.root/'ASSET-SHA256.json').read_text())
    for name, digest in manifest.items():
        assert hashlib.sha256((args.root/name).read_bytes()).hexdigest() == digest, name
    records = [audit(case) for case in sorted((args.root/'results').iterdir()) if (case/'exit.json').exists()]
    comparisons = []
    for e in (8,32):
        item = dict(E=e, M=2, source='mean of two per-process medians in BF16/FP8/FP8/BF16 order')
        for mode in ('bf16','fp8'):
            rs = [r for r in records if 'event_median_us' in r and not r['profiled']
                  and r['plan']['E'] == e and r['plan']['mode'] == mode]
            assert len(rs) == 2
            event = statistics.mean(r['event_median_us'] for r in rs)
            item[mode] = dict(event_us=event, equivalent_only_TBps=rs[0]['plan']['mxfp4_equivalent_bytes']/event/1e6,
                              cases=[r['case'] for r in rs])
        item['speedup'] = item['bf16']['event_us']/item['fp8']['event_us']
        comparisons.append(item)
    result = dict(scope='Generated SRAM feed only. No real MXFP4, activation quantization or model result.',
                  asset_sha256_verified_count=len(manifest), records=records, abba=comparisons)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2)+'\n')
    print(json.dumps(dict(cases=len(records), abba=comparisons), indent=2))
